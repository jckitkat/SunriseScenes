// npm run smoke
// Starts the built desktop app twice with no window, against a throwaway copy of the
// fixture Sunrise folder and a throwaway profile. The first run opens, edits and saves
// missions; the second checks the app came back exactly where the first one stopped.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url)), project = path.join(here, '..');
const electron = createRequire(import.meta.url)('electron');   // the path to the Electron binary
if (!fs.existsSync(path.join(project, 'dist', 'index.html'))) { console.error('Build first: npm run build'); process.exit(1); }

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'sunrise-scenes-smoke-'));
const root = path.join(tmp, 'game', 'bin', 'x64', 'Sunrise');
fs.cpSync(path.join(project, 'tests', 'fixtures', 'Sunrise'), root, { recursive: true });
// And a plain folder holding only scripts, like a copy of the missions repository.
fs.cpSync(path.join(project, 'tests', 'fixtures', 'Sunrise', 'scripts'), path.join(tmp, 'plain'), { recursive: true });
// Point at the game folder, two levels above, so finding the Sunrise folder is exercised too.
const env = { ...process.env, SUNRISE_SCENES_ROOT: path.join(tmp, 'game'), SUNRISE_SCENES_USERDATA: path.join(tmp, 'profile'), ELECTRON_ENABLE_LOGGING: '0' };

// SMOKE_EXE=<path to a packaged "Sunrise Scenes.exe"> checks the packaged app instead.
const packaged = process.env.SMOKE_EXE;
function launch(label) {
  const r = spawnSync(packaged || electron, packaged ? ['--smoke'] : ['.', '--smoke'], { cwd: project, env, encoding: 'utf8', timeout: 60000 });
  const line = (r.stdout || '').split('\n').find((l) => l.startsWith('SMOKE '));
  for (const l of (r.stdout || '').split('\n')) if (l.startsWith('PAGE ')) console.log('  page: ' + l.slice(5));
  if (!line) { console.error(`${label}: the app printed no result (exit ${r.status}).\n${r.stderr || ''}`); process.exit(1); }
  return JSON.parse(line.slice(6));
}
let failed = false;
const show = (name, pass, detail) => { console.log(`${pass ? '  ok  ' : '  FAIL'} ${name}${detail ? '  —  ' + detail : ''}`); if (!pass) failed = true; };

console.log('First launch');
const a = launch('first launch');
for (const s of a.steps) show(s.name, s.pass, s.detail);
if (a.error) show('no error in the page', false, a.error);

const demo = path.join(root, 'scripts', 'mission_demo');
show('the script on disk was written by the app', fs.readFileSync(path.join(demo, 'mission_demo.lua'), 'utf8').includes('Generated by Sunrise Scenes'));
show('the hand-written script was kept as .bak', fs.existsSync(path.join(demo, 'mission_demo.lua.bak')));
show('the drawing was saved beside it', fs.existsSync(path.join(demo, 'mission_demo.scene.json')));
show('the plain folder got its script and backup', fs.readFileSync(path.join(tmp, 'plain', 'mission_demo', 'mission_demo.lua'), 'utf8').includes('Generated by Sunrise Scenes')
  && fs.existsSync(path.join(tmp, 'plain', 'mission_demo', 'mission_demo.lua.bak')));
show('the freeroam content.lua was backed up before being replaced', fs.existsSync(path.join(root, 'scripts', 'demo_freeroam', 'content.lua.bak')));
show('the workspace file exists', fs.existsSync(path.join(tmp, 'profile', 'workspace.json')));

console.log('Second launch');
const b = launch('second launch');
for (const s of b.steps) show(s.name, s.pass, s.detail);
const r = b.restored || {}, left = a.left || {};
show('the same mission is open', r.mission && r.mission.name === left.mission, JSON.stringify(r.mission));
show('the same screen is showing', r.view === left.view, r.view);
show('zoom and pan are back', r.zoom === left.zoom && r.pan && r.pan.x === left.pan.x && r.pan.y === left.pan.y, `${r.zoom} @ ${JSON.stringify(r.pan)}`);
show('the drawing is back', r.nodes === left.nodes && r.nodes > 0, r.nodes + ' nodes');
show('SDK keys were loaded again', r.sdkKeys > 0, r.sdkKeys + ' keys');

fs.rmSync(tmp, { recursive: true, force: true });
console.log(failed ? '\nSmoke run FAILED' : '\nSmoke run passed');
process.exit(failed ? 1 : 0);
