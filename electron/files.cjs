// Everything the desktop app does on disk: finding where the scripts are, listing
// missions, reading and writing scripts, and finding a mission's generated SDK module.
// Plain Node (no Electron), so the tests can run it against a fixture folder.
//
// "root" is one of two things:
//   - a Sunrise install folder, <game>/bin/x64/Sunrise, holding scripts/ and sdk/lua/; or
//   - a plain scripts folder: any folder whose subfolders are <name>/<name>.lua, such as a
//     clone of the missions repository.
// A plain folder has no SDK of its own, so the functions that need one take an optional
// "sdkDir": a folder holding missions.lua (a Sunrise install's sdk/lua).
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');

const NAME = /^[a-z0-9_]+$/;   // a script stem; also keeps every path inside the scripts folder
const FILE = /^[a-z0-9_]+\.lua$/;   // a Lua file inside a mission's folder
const MARK = 'Generated by Sunrise Scenes';
const exists = (p) => { try { fs.accessSync(p); return true; } catch { return false; } };
const isDir = (p) => { try { return fs.statSync(p).isDirectory(); } catch { return false; } };
const read = (p) => { try { return fs.readFileSync(p, 'utf8'); } catch { return null; } };
const subdirs = (p) => { try { return fs.readdirSync(p, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name); } catch { return []; } };

const isInstall = (p) => isDir(path.join(p, 'sdk', 'lua')) || (path.basename(p).toLowerCase() === 'sunrise' && isDir(path.join(p, 'scripts')));
// Where a root keeps its scripts, and where its SDK is (null when it has none).
const scriptsOf = (root) => (isInstall(root) ? path.join(root, 'scripts') : root);
const sdkOf = (root, sdkDir) => (isInstall(root) ? path.join(root, 'sdk', 'lua') : resolveSdk(sdkDir));

// A folder below `dir`, each name matched without regard to case. Windows does not care how
// "bin/x64/Sunrise" is capitalised; Linux does, and the game folder there is a Windows one
// (run through Proton or Wine), so it may be spelled either way.
function below(dir, ...names) {
  let p = dir;
  for (const name of names) {
    const exact = path.join(p, name);
    if (isDir(exact)) { p = exact; continue; }
    const other = subdirs(p).find((n) => n.toLowerCase() === name.toLowerCase());
    if (!other) return exact;   // not there under any spelling; the caller's check will fail
    p = path.join(p, other);
  }
  return p;
}
// A picked folder that is, or holds, a Sunrise install: the Sunrise folder itself, the game
// folder, bin/x64 inside it, or the install's own scripts folder.
function resolveInstall(picked) {
  if (!picked) return null;
  const up = path.dirname(picked);
  for (const p of [picked, below(picked, 'Sunrise'), below(picked, 'x64', 'Sunrise'), below(picked, 'bin', 'x64', 'Sunrise')]) if (isInstall(p)) return p;
  if (path.basename(picked).toLowerCase() === 'scripts' && isInstall(up)) return up;
  return null;
}
// A picked folder that holds a generated SDK: sdk/lua itself, sdk, or anything an install resolves from.
function resolveSdk(picked) {
  if (!picked) return null;
  const install = resolveInstall(picked);
  for (const p of [picked, path.join(picked, 'lua'), path.join(picked, 'sdk', 'lua'), install && path.join(install, 'sdk', 'lua')]) {
    if (p && exists(path.join(p, 'missions.lua'))) return p;
  }
  return null;
}
// Does this folder directly hold scripts (at least one <name>/<name>.lua)?
const holdsScripts = (p) => subdirs(p).some((n) => exists(path.join(p, n, n + '.lua')));

// Where the Sunrise launcher keeps its preferences. On Windows that is known. On Linux it is
// a guess at the usual places for an app of that name; nobody has seen the launcher there.
const LAUNCHER = 'io.github.stanuwu.sunrise-launcher';
function launcherPrefs(env = process.env, home = os.homedir(), platform = process.platform) {
  if (platform === 'win32') return [path.join(env.LOCALAPPDATA || path.join(home, 'AppData', 'Local'), LAUNCHER, 'preferences.json')];
  if (platform === 'darwin') return [path.join(home, 'Library', 'Application Support', LAUNCHER, 'preferences.json')];
  return [env.XDG_CONFIG_HOME || path.join(home, '.config'), env.XDG_DATA_HOME || path.join(home, '.local', 'share')].map((d) => path.join(d, LAUNCHER, 'preferences.json'));
}
// A folder a Windows program wrote down, as this system names it. Under Wine and Proton the
// Z: drive is the whole Linux filesystem, so "Z:\\home\\me\\Games" is /home/me/Games.
function nativeDir(dir, platform = process.platform) {
  if (platform === 'win32' || typeof dir !== 'string') return dir;
  const z = dir.match(/^[zZ]:[\\/](.*)$/);
  return z ? '/' + z[1].replace(/\\/g, '/') : dir;
}
// Look for a Sunrise install where the launcher says the game is (and in any extra places).
function findSunrise(extra = []) {
  const starts = [...extra];
  for (const file of launcherPrefs()) {
    const prefs = read(file);
    if (prefs) { try { const dir = nativeDir(JSON.parse(prefs).installDirectory); if (dir) starts.push(dir); } catch { /* unreadable preferences: skip */ } }
  }
  return searchBelow(starts);
}
// An install at one of these folders, or up to two folders below one.
function searchBelow(starts) {
  for (const start of starts) {
    const direct = resolveInstall(start);
    if (direct) return direct;
    let level = [start];
    for (let depth = 0; depth < 2; depth++) {
      const next = [];
      for (const dir of level) {
        for (const n of subdirs(dir).filter((x) => !x.startsWith('.') && x !== 'node_modules').slice(0, 200)) {
          const p = path.join(dir, n), r = resolveInstall(p);
          if (r) return r;
          next.push(p);
        }
      }
      level = next.slice(0, 400);
    }
  }
  return null;
}

// What a folder the user picked should be opened as. A folder that already holds scripts is
// taken as it is; otherwise an install in or just below it; otherwise the folder itself, as
// an empty scripts folder to start filling.
function chooseRoot(picked) {
  if (!isDir(picked)) return null;
  const install = resolveInstall(picked);
  if (install) return install;
  if (holdsScripts(picked)) return picked;
  return searchBelow([picked]) || picked;
}
// Facts about a root for the page to show.
function describeRoot(root, sdkDir) {
  if (!root || !isDir(root)) return null;
  return { root, kind: isInstall(root) ? 'install' : 'scripts', scripts: scriptsOf(root), sdk: sdkOf(root, sdkDir) || '' };
}

const scriptDir = (root, name) => path.join(scriptsOf(root), name);
const luaPath = (root, name) => path.join(scriptDir(root, name), name + '.lua');
const scenePath = (root, name) => path.join(scriptDir(root, name), name + '.scene.json');
function checkName(name) { if (!NAME.test(name || '')) throw new Error('not a script name: ' + name); }

// The Lua files in a mission's folder, main script first.
function luaFiles(root, name) {
  let names = [];
  try { names = fs.readdirSync(scriptDir(root, name)).filter((n) => FILE.test(n)).sort(); } catch { /* no such folder */ }
  const main = name + '.lua';
  return names.includes(main) ? [main, ...names.filter((n) => n !== main)] : names;
}

// NAME = "module.path" entries of sdk/lua/missions.lua or activities.lua.
function nameTable(text) {
  const out = new Map();
  for (const m of (text || '').matchAll(/([A-Za-z0-9_]+)\s*=\s*"([a-z]+\.[A-Za-z0-9_.]+)"/g)) out.set(m[1], m[2]);
  return out;
}
const fold = (name) => { let s = name.toLowerCase().replace(/[^a-z0-9]+/g, '_'); if (!s) s = 'unnamed'; return /^[0-9]/.test(s) ? '_' + s : s; };

// What kind of script a file is, from its text.
function classify(lua, hasScene, helpers) {
  if (hasScene) return 'scene';                                    // drawn here; opens exactly as saved
  if (lua == null) return helpers ? 'helpers' : 'none';            // a folder of shared Lua with no script of its own
  if (/\bcampaign\.new\s*[{(]/.test(lua)) return 'campaign';       // hand-written lib.campaign: can be drawn
  if (/\bfreeroam\.new\s*[{(]/.test(lua)) return 'freeroam';       // open-world destination: can be drawn
  return 'lua';                                                    // anything else: text editor
}

// Every script folder, plus the activities the SDK knows that have no script yet.
function listMissions(root, sdkDir) {
  const out = [], seen = new Set();
  for (const name of subdirs(scriptsOf(root)).sort()) {
    if (!NAME.test(name)) continue;
    const lua = read(luaPath(root, name)), others = luaFiles(root, name);
    if (lua == null && !exists(scenePath(root, name)) && !others.length) continue;   // nothing of ours in there
    const m = lua && lua.match(/require\(\s*(?:assert\(\s*)?missions\.([A-Za-z0-9_]+)/);
    out.push({ name, kind: classify(lua, exists(scenePath(root, name)), others.length > 0), scenario: m ? m[1] : '', bytes: lua ? lua.length : 0, files: others.length });
    seen.add(name);
  }
  const sdk = sdkOf(root, sdkDir);
  if (sdk) for (const key of nameTable(read(path.join(sdk, 'activities.lua'))).keys()) {
    const name = fold(key);
    if (!seen.has(name)) { seen.add(name); out.push({ name, kind: 'none', scenario: '', bytes: 0 }); }
  }
  return out;
}

// The generated mission module for a scenario key, or for an activity name when the key is
// not known. Returns { key, path, text } with text null when the file is not there.
function sdkFor(root, scenario, activity, sdkDir) {
  const sdk = sdkOf(root, sdkDir);
  if (!sdk) return { key: scenario || '', path: '', text: null, none: true };
  const missions = nameTable(read(path.join(sdk, 'missions.lua')));
  let key = scenario && missions.has(scenario) ? scenario : '';
  if (!key && activity) {
    // The activity module requires its mission module; find that module's key in missions.lua.
    const acts = nameTable(read(path.join(sdk, 'activities.lua')));
    const actKey = [...acts.keys()].find((k) => fold(k) === activity);
    const text = actKey ? read(path.join(sdk, ...acts.get(actKey).split('.')) + '.lua') : null;
    const m = text && text.match(/missions\.([A-Za-z0-9_]+)/);
    if (m) key = [...missions.keys()].find((k) => missions.get(k) === 'missions.' + m[1] || k === m[1]) || '';
    if (!key && missions.has(activity.toUpperCase())) key = activity.toUpperCase();
  }
  if (!key) return { key: scenario || '', path: '', text: null };
  const file = path.join(sdk, ...missions.get(key).split('.')) + '.lua';
  return { key, path: file, text: read(file) };
}

function readMission(root, name, sdkDir) {
  checkName(name);
  const lua = read(luaPath(root, name)), scene = read(scenePath(root, name));
  let scenario = '';
  if (scene) { try { scenario = JSON.parse(scene).meta.scenario || ''; } catch { /* a broken sidecar: fall back to the Lua */ } }
  const m = lua && lua.match(/require\(\s*(?:assert\(\s*)?missions\.([A-Za-z0-9_]+)/);
  if (!scenario && m) scenario = m[1];
  // Every Lua file in the folder: a mission may keep its data or helpers in further files.
  const files = {};
  for (const n of luaFiles(root, name)) files[n] = read(path.join(scriptDir(root, name), n)) || '';
  return { name, lua, scene, files, kind: classify(lua, !!scene, Object.keys(files).length > 0), generated: !!lua && lua.includes(MARK),
    path: lua != null ? luaPath(root, name) : scriptDir(root, name), sdk: sdkFor(root, scenario, name, sdkDir) };
}

// Write a mission. A file this app did not generate is copied to <file>.bak once, before
// it is first replaced. lua is the main script (null to leave it alone), scene the drawing
// (JSON text, or null for a text edit), extra any further Lua files by file name.
function writeMission(root, name, lua, scene, extra = {}) {
  checkName(name);
  if (!isDir(root)) throw new Error('that folder no longer exists: ' + root);
  for (const n of Object.keys(extra)) if (!FILE.test(n)) throw new Error('not a Lua file name: ' + n);
  fs.mkdirSync(scriptDir(root, name), { recursive: true });
  const backups = [];
  const put = (file, text) => {
    const old = read(file), backup = file + '.bak';
    if (old === text) return;
    if (old != null && !old.includes(MARK) && !exists(backup)) { fs.writeFileSync(backup, old); backups.push(backup); }
    fs.writeFileSync(file, text);
  };
  if (lua != null) put(luaPath(root, name), lua);
  for (const [n, text] of Object.entries(extra)) put(path.join(scriptDir(root, name), n), text);
  if (scene != null) fs.writeFileSync(scenePath(root, name), scene);
  return { path: luaPath(root, name), backup: backups[0] || '', backups };
}

module.exports = { resolveInstall, resolveSdk, chooseRoot, describeRoot, findSunrise, listMissions, readMission, writeMission, sdkFor, read, isDir, MARK, launcherPrefs, nativeDir };
