// What both export modes share: the problem list, the file header, the input table, and
// turning a custom node's Lua into finished code.
import { T, KINDS, LUA_KEYWORDS, VALID_KEY } from '../catalog.js';
import { lintDef } from '../lualint.js';

export function foldStem(name) {
  let s = (name || '').toLowerCase().replace(/[^a-z0-9]+/g, '_');
  if (!s) s = 'unnamed';
  if (/^[0-9]/.test(s)) s = '_' + s;
  return s;
}
export const ind = (text, n) => text.split('\n').map((l) => (l ? ' '.repeat(n) + l : l)).join('\n');
export const luaString = (s) => '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n') + '"';
const luaField = (name) => (LUA_KEYWORDS.has(name) ? name + '_' : name);

export function compilerBase(doc) {
  const problems = [];
  const err = (msg, nid) => problems.push({ msg, nid, level: 'err' });
  const warn = (msg, nid) => problems.push({ msg, nid, level: 'warn' });
  const inputs = new Map(doc.inputs.map((i) => [i.id, i]));
  const byName = new Map(doc.inputs.map((i) => [i.name, i]));
  const stem = foldStem(doc.meta.activity);
  const scenario = (doc.meta.scenario || '').trim();

  if (!doc.meta.activity.trim()) err('Set the activity name (top bar). The script file is named after it.');
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(scenario)) err('Set the scenario key from sdk/lua/missions.lua (top bar).');

  const usedInputs = new Set(), twins = new Set();
  const refOf = (id) => { usedInputs.add(id); return 'input.' + luaField(inputs.get(id).name); };
  // A squad or scene shares its key with its slot; the twin is the mission.Slot entry.
  const twinOf = (id) => { usedInputs.add(id); twins.add(id); return 'input.' + inputs.get(id).name + '__slot'; };
  // The Lua expression for an input, or null when it is unset or of another kind.
  const pick = (id, kind) => { const i = inputs.get(id); return i && i.kind === kind ? refOf(id) : null; };
  const head = (requires) => [`-- ${stem}.lua`, '-- Generated by Sunrise Scenes. Change the scene and export again; edits here are lost.',
    `-- Install as: <game>/bin/x64/Sunrise/scripts/${stem}/${stem}.lua`, '',
    'local missions = require("missions")',
    `local mission = require(assert(missions.${scenario || 'MY_SCENARIO'}, "unknown scenario: ${scenario || 'MY_SCENARIO'}"))`,
    'local lib = require("lib.mission_lib")', ...requires, ''];
  // Call last: it lists, and checks, only the inputs something used.
  const inputTable = () => {
    const L = ['-- Inputs: every name the scene uses. A wrong key fails here, when the file loads.', 'local input = {'];
    const seen = new Set();
    for (const i of doc.inputs) {
      if (!usedInputs.has(i.id)) continue;
      if (!/^[a-z_][a-z0-9_]*$/.test(i.name)) err(`Input "${i.name}" needs a name made of a-z, 0-9 and _.`);
      if (seen.has(i.name)) err(`Two inputs are both named "${i.name}".`);
      seen.add(i.name);
      if (!VALID_KEY.test(i.key)) err(`Input "${i.name}" has no valid ${KINDS[i.kind]} key. Set it on the Inputs screen.`);
      const key = VALID_KEY.test(i.key) ? i.key : 'MISSING_KEY';
      L.push(`    ${luaField(i.name)} = lib.one(${KINDS[i.kind]}.${key}, "${i.name}"),`);
      if (twins.has(i.id)) L.push(`    ${i.name}__slot = lib.one(mission.Slot.${key}, "${i.name} slot"),`);
    }
    L.push('}', '');
    return L;
  };

  // Lua written by the user, with its {socket} placeholders replaced by what the node holds.
  // Hand-written input.name references are honoured too, so the input table includes them.
  const fillLua = (code, n, nid) => {
    const sockets = new Map(T(n.type).parts.filter((p) => p.text == null).map((p) => [p.name, p]));
    const out = code.replace(/\{(\w+)(\.slot)?\}/g, (whole, name, slot) => {
      if (name === 'node') return luaString('n' + n.id);
      const p = sockets.get(name), v = n.params[name];
      if (!p) return whole;
      if (p.kind === 'enum') { const k = p.options.indexOf(v); return p.values[k < 0 ? 0 : k]; }
      if (p.kind === 'num') return String(Number(v) || 0);
      if (p.kind === 'flag') return v ? 'true' : 'false';
      if (p.kind === 'text') return luaString(v || '');
      if (p.kind !== 'ref') return whole;
      const one = (id) => (pick(id, p.ref) ? (slot ? twinOf(id) : refOf(id)) : null);
      return p.list ? '{' + (v || []).map(one).filter(Boolean).join(', ') + '}' : one(v) || 'nil';
    });
    for (const m of out.matchAll(/\binput\.([A-Za-z_][A-Za-z0-9_]*)/g)) {
      const slot = m[1].endsWith('__slot'), i = byName.get(slot ? m[1].slice(0, -6) : m[1]);
      if (!i) err(`This Lua names input.${m[1]}, but there is no input called that.`, nid);
      else if (slot) twinOf(i.id); else usedInputs.add(i.id);
    }
    return out.replace(/\s+$/, '');
  };
  // A custom node is only as good as its definition; report a broken one once, where it is used.
  const reported = new Set();
  const defOk = (def, nid) => {
    const { errors } = lintDef(def);
    if (errors.length && !reported.has(def.id)) { reported.add(def.id); err(`Custom node "${def.template}": ${errors[0]} Fix it on the Nodes screen.`, nid); }
    return !errors.length;
  };
  // Check that a custom node has everything its sentence asks for.
  const socketsFilled = (n, nid, say) => {
    let ok = true;
    for (const p of T(n.type).parts) {
      if (p.kind !== 'ref' || p.optional) continue;
      const v = n.params[p.name], full = p.list ? (v || []).some((id) => pick(id, p.ref)) : !!pick(v, p.ref);
      if (!full) { err(`"${say}" is missing its ${p.name}.`, nid); ok = false; }
    }
    return ok;
  };
  return { problems, err, warn, inputs, stem, usedInputs, refOf, twinOf, pick, head, inputTable, fillLua, defOk, socketsFilled, luaField };
}
